// Legal exceptions are intentionally local and bounded. They must contain every
// stated safeguard in one short sentence, never merely somewhere in the contract.
const sentenceBody = '[^。；;！？!?\\r\\n]';
function localException(conditions: string[], conflicts: string): RegExp {
  return new RegExp(`(?:^|[。；;！？!?\\r\\n])${conditions.map(condition => `(?=${sentenceBody}{0,240}(?:${condition}))`).join('')}(?!${sentenceBody}{0,240}(?:${conflicts}))${sentenceBody}{1,240}(?=$|[。；;！？!?\\r\\n])`);
}

